def build_context(docs: list[dict]) -> str:
    if not docs:
        return "База знаний: релевантная информация не найдена."
    parts = ["База знаний. Используй только эти фрагменты:\n"]
    for i, doc in enumerate(docs, 1):
        parts.append(
            f"[Источник {i}: {doc['source']}, score={doc.get('score', 0)}]\n"
            f"{doc['content'][:1200]}"
        )
    return "\n\n".join(parts)


def should_add_sales_cta(intent: str) -> bool:
    role = settings.BOT_ROLE.lower()
    if role == "seller":
        return intent in ("QUESTION", "BUY", "LEAD")
    if role == "hybrid":
        return intent == "BUY"
    return False


def check_limits(db: Database) -> tuple[bool, str]:
    today = db.get_today_stats(TENANT_ID)
    month = db.get_month_stats(TENANT_ID)
    if today["requests"] >= settings.DAILY_REQUEST_LIMIT:
        return False, "Дневной лимит обращений исчерпан. Попробуйте завтра."
    if month["tokens"] >= settings.MONTHLY_TOKEN_LIMIT:
        return False, "Месячный лимит токенов исчерпан. Обратитесь к администратору."
    return True, ""
